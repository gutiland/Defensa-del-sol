export function drawCampingTent(ctx, base = false, level = 1) {
  ctx.save();
  ctx.lineJoin = "round";
  ctx.lineCap = "round";
  ctx.strokeStyle = "#34432a";
  ctx.lineWidth = 2.3;
  if (level === 1) {
    ctx.fillStyle = "#4b49352b";
    ctx.fillRect(-35, 20, 72, 9);
    ctx.fillStyle = base ? "#a99959" : "#99927a";
    ctx.beginPath();
    ctx.moveTo(-37, 23);
    ctx.lineTo(-6, -22);
    ctx.lineTo(34, 21);
    ctx.lineTo(5, 27);
    ctx.closePath();
    ctx.fill();
    ctx.stroke();
    ctx.fillStyle = "#413d32";
    ctx.beginPath();
    ctx.moveTo(-23, 23);
    ctx.lineTo(-6, -22);
    ctx.lineTo(4, 25);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = "#b9ac87";
    ctx.fillRect(8, 3, 13, 10);
    ctx.strokeRect(8, 3, 13, 10);
    ctx.strokeStyle = "#746248";
    ctx.lineWidth = 1.2;
    ctx.beginPath();
    ctx.moveTo(-6, -22);
    ctx.lineTo(-49, 28);
    ctx.moveTo(-6, -22);
    ctx.lineTo(47, 27);
    ctx.stroke();
    ctx.fillStyle = "#6a5740";
    ctx.fillRect(-50, 24, 3, 8);
    ctx.fillRect(46, 23, 3, 8);
    ctx.restore();
    return;
  }
  if (level >= 3) {
    ctx.fillStyle = "#a6854b";
    ctx.fillRect(-40, 23, 81, 9);
    ctx.strokeRect(-40, 23, 81, 9);
  }
  if (base) ctx.scale(1.1, 1.1);
  ctx.fillStyle = "#26392130";
  ctx.beginPath();
  ctx.ellipse(5, 23, 40, 13, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = base ? "#e5b946" : level === 2 ? "#84906a" : "#8db74d";
  ctx.beginPath();
  ctx.moveTo(-36, 21);
  ctx.bezierCurveTo(-38, -7, -18, -34, 7, -27);
  ctx.bezierCurveTo(27, -23, 40, 4, 37, 23);
  ctx.quadraticCurveTo(0, 37, -36, 21);
  ctx.fill();
  ctx.stroke();
  ctx.fillStyle = base ? "#c58e31" : "#68943b";
  ctx.beginPath();
  ctx.moveTo(4, -25);
  ctx.bezierCurveTo(26, -15, 25, 12, 37, 23);
  ctx.quadraticCurveTo(13, 31, 0, 29);
  ctx.lineTo(4, -25);
  ctx.fill();
  ctx.fillStyle = "#263d2c";
  ctx.beginPath();
  ctx.moveTo(-21, 24);
  ctx.bezierCurveTo(-21, 6, -12, -16, -1, -15);
  ctx.quadraticCurveTo(12, -7, 14, 27);
  ctx.closePath();
  ctx.fill();
  ctx.stroke();
  ctx.fillStyle = base ? "#f3d46a" : "#b7d86e";
  ctx.beginPath();
  ctx.moveTo(-1, -15);
  ctx.quadraticCurveTo(-1, 12, -21, 24);
  ctx.lineTo(-17, 5);
  ctx.closePath();
  ctx.fill();
  ctx.stroke();
  ctx.strokeStyle = "#e4e5ad";
  ctx.lineWidth = 2.3;
  ctx.beginPath();
  ctx.moveTo(-32, 19);
  ctx.bezierCurveTo(-25, -26, 5, -38, 33, 21);
  ctx.stroke();
  ctx.strokeStyle = "#34432a";
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(-30, 7);
  ctx.lineTo(-44, 27);
  ctx.moveTo(30, 6);
  ctx.lineTo(45, 27);
  ctx.stroke();
  ctx.fillStyle = "#738445";
  ctx.fillRect(-46, 26, 5, 3);
  ctx.fillRect(43, 26, 5, 3);
  ctx.strokeStyle = "#f4f0b67a";
  ctx.lineWidth = 3;
  ctx.beginPath();
  ctx.moveTo(-27, -4);
  ctx.quadraticCurveTo(-24, -16, -15, -20);
  ctx.stroke();
  if (level >= 3) {
    ctx.strokeStyle = "#e5c773";
    ctx.lineWidth = 2;
    ctx.strokeRect(-24, 22, 50, 6);
    ctx.fillStyle = "#fff1a0";
    ctx.fillRect(24, -8, 7, 10);
  }
  if (level >= 4) {
    ctx.fillStyle = "#e7cc78";
    ctx.fillRect(-28, -30, 55, 8);
    ctx.strokeStyle = "#665036";
    ctx.strokeRect(-28, -30, 55, 8);
    ctx.fillStyle = "#c95b4a";
    ctx.beginPath();
    ctx.moveTo(-31, -22);
    ctx.lineTo(28, -22);
    ctx.lineTo(34, -12);
    ctx.lineTo(-36, -12);
    ctx.closePath();
    ctx.fill();
    ctx.fillStyle = "#7eab61";
    ctx.fillRect(-43, 12, 9, 12);
    ctx.fillRect(35, 12, 9, 12);
  }
  ctx.restore();
}
